import { readFile, writeFile } from 'node:fs/promises'
import { stages } from '../server/data/courses.js'
import { catalogueStage } from '../server/services/course-outline.js'
import { capstoneLessons, capstoneTotal, capstoneEstimatedTotalTime } from '../server/data/capstoneLessons.js'
import { capstoneShowcase } from '../server/data/capstoneShowcase.js'

const source = (await readFile('server/data/courses.ts', 'utf8')).replace(/\r\n/g, '\n')
const start = source.indexOf('export const stages: Stage[] = [')
const end = source.indexOf('\n]\n', start) + 2
if (start < 0 || end < start) throw new Error('Cannot locate canonical curriculum')
const publicData = stages.map(stage => catalogueStage(stage, false))
const output = '// Generated by npm run build:catalogue. Edit server/data/courses.ts instead.\n' + source.slice(0, start) + 'export const stages: Stage[] = ' + JSON.stringify(publicData, null, 2) + source.slice(end)
if (process.argv.includes('--check')) {
  if (await readFile('src/data/courses.ts', 'utf8') !== output) throw new Error('Public curriculum is stale. Run npm run build:catalogue.')
} else await writeFile('src/data/courses.ts', output)
console.info('PASS: public curriculum contains only stage overviews and free preview metadata.')

const publicLessons = capstoneLessons.map(lesson => ({ ...lesson,
  title: lesson.id === 'c1' ? lesson.title : `项目工坊第 ${lesson.order} 课`, checkKeys: [], contentPath: '',
}))
const publicShowcase = { ...capstoneShowcase, lessons: capstoneShowcase.lessons.map((lesson, index) => ({
  code: lesson.code, phase: '', title: index === 0 ? lesson.title : `项目工坊第 ${index + 1} 课`, desc: '',
})) }
const generated = new Map([
  ['src/data/capstoneLessons.ts', '// Generated by npm run build:catalogue. Edit server/data/capstoneLessons.ts instead.\n' +
    'export type CapstoneLesson = { id: string; title: string; order: number; estimatedTime: string; published: boolean; checkKeys: string[]; contentPath: string }\n' +
    'export const capstoneLessons: CapstoneLesson[] = ' + JSON.stringify(publicLessons, null, 2) + '\n' +
    `export const capstoneTotal = ${capstoneTotal}\nexport const capstoneEstimatedTotalTime = ${JSON.stringify(capstoneEstimatedTotalTime)}\n` +
    'export function capstoneLesson(id: string) { return capstoneLessons.find(lesson => lesson.id === id && lesson.published) }\n'],
  ['src/data/capstoneShowcase.ts', '// Generated by npm run build:catalogue. Edit server/data/capstoneShowcase.ts instead.\nexport const capstoneShowcase = ' + JSON.stringify(publicShowcase, null, 2) + ' as const\n'],
])
for (const [file, text] of generated) {
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== text) throw new Error(`Public Project Lab metadata is stale: ${file}`)
  } else await writeFile(file, text)
}
console.info('PASS: public Project Lab metadata omits the protected lesson outline.')
