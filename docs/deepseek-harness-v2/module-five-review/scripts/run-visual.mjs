import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const here=fileURLToPath(new URL('../',import.meta.url)),repo=resolve(here,'../../..'),h=process.argv[2];
if(!['h17','h18','h19','h20'].includes(h))throw Error('choose h17-h20');
const original=resolve(here,'..',h),out=resolve(here,'evidence',h,'visual');
await mkdir(resolve(out,'figures/qa'),{recursive:true});await mkdir(resolve(out,'evidence'),{recursive:true});
let code=await readFile(resolve(original,'scripts/preview-and-qa.tsx'),'utf8');
code=code.replace("fileURLToPath(new URL('../',import.meta.url))",JSON.stringify(original));
code=code.replaceAll('path:resolve(root,','path:resolve('+JSON.stringify(out)+',');
code=code.replaceAll("mkdir(resolve(root,'figures/qa')","mkdir(resolve("+JSON.stringify(out)+",'figures/qa')");
code=code.replaceAll('writeFile(resolve(root,','writeFile(resolve('+JSON.stringify(out)+',');
if(h==='h17')code=code.replace('  const metrics=await page.evaluate',`  await page.getByRole('heading',{name:'五个核心文件：每读一站交一个结果'}).evaluate(e=>scrollTo(0,scrollY+e.getBoundingClientRect().top-15));
  await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  await page.screenshot({path:resolve(${JSON.stringify(out)},\`figures/qa/reading-route-\${width}.png\`)});
  const metrics=await page.evaluate`);
const generated=resolve(here,'scripts',`qa-${h}.tsx`);await writeFile(generated,code);
const args=[resolve(repo,'node_modules/tsx/dist/cli.mjs'),generated];
const r=spawnSync(process.execPath,args,{cwd:repo,encoding:'utf8',timeout:240000,maxBuffer:10*1024*1024});
await writeFile(resolve(out,`run-${Date.now()}.json`),JSON.stringify({command:`node docs/deepseek-harness-v2/module-five-review/scripts/run-visual.mjs ${h}`,exit:r.status,stdout:r.stdout,stderr:r.stderr,error:r.error?String(r.error):null},null,2)+'\n');
process.stdout.write(r.stdout??'');process.stderr.write(r.stderr??'');process.exitCode=r.status??1;
